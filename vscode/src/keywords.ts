/** The help for the word at a position, allowing for keywords that end in $, # or (. */
export function helpFor(word: string, next: string): KeywordHelp | undefined {
    const upper = word.toUpperCase();
    return keywordHelp[upper + next] ?? keywordHelp[upper];
}
